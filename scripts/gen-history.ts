import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { asArray, asNumber, asObject, asString, readJson, repoRoot } from "./lib/fixtures.ts";
import type { Json } from "./lib/fixtures.ts";

interface Source {
  vector: string;
  file: string;
  account: string;
  kind: "agent" | "creator";
}

const sources: Source[] = [
  { vector: "steady-diversified", file: "biz-agent.json", account: "biz-agent.testnet", kind: "agent" },
  { vector: "spiky-creator", file: "luna.json", account: "luna.testnet", kind: "creator" },
];

const vectors = asArray(readJson("contracts/fixtures/underwriting-vectors.json"), "underwriting-vectors").map((v) =>
  asObject(v, "vector"),
);
const outDir = join(repoRoot, "deployments", "history");
mkdirSync(outDir, { recursive: true });

for (const source of sources) {
  const vector = vectors.find((v) => v.name === source.vector);
  if (vector === undefined) {
    throw new Error(`vector ${source.vector} not found`);
  }
  const inflows: Json[] = asArray(vector.inflows, "inflows").map((raw) => {
    const inflow = asObject(raw, "inflow");
    return {
      day: asNumber(inflow.day, "day"),
      amount: asString(inflow.amount, "amount"),
      payer: asString(inflow.payer, "payer"),
    };
  });
  const document: Json = {
    source: "fixture",
    note: "Synthetic seed history for the demo. Not live on-chain history. Generated by scripts/gen-history.ts from contracts/fixtures/underwriting-vectors.json.",
    account: source.account,
    kind: source.kind,
    routed_share_bps: asNumber(vector.routed_share_bps, "routed_share_bps"),
    inflows,
  };
  writeFileSync(join(outDir, source.file), `${JSON.stringify(document, null, 2)}\n`);
  console.log(`wrote deployments/history/${source.file} (${inflows.length} inflows, source: fixture)`);
}
